"""Cut the painted plunger into live sprites and clear it from the playfield (run after prepare_art.py).

knob.png   - the emerald gem with its brass cap (moves down when the plunger is pulled)
spring.png - the coil spring (compresses: drawn scaled, anchored at its bottom ring)
playfield.jpg is patched in place: the area under the moving parts is filled from the lane around it,
so nothing is doubled when the knob moves.

Usage: python3 plunger_art.py <artdir>
(the sprites are cut from playfield.jpg itself, which is already in painting coordinates; run it once on a fresh
playfield.jpg from prepare_art.py – a second run would cut from the already-cleared area)
"""
import sys, json
import numpy as np
import cv2
from PIL import Image, ImageDraw, ImageFilter

out = sys.argv[1]
src = Image.open(f'{out}/playfield.jpg').convert('RGBA')
W, H = src.size

GEM = (1189, 1761, 57, 55)  # cx, cy, rx, ry
CAP = (1136, 1812, 1243, 1852)  # brass cap under the gem
SPRING = (1158, 1846, 1247, 2027)  # coils, down to the fixed bottom ring


def cut(name, shapes):
    m = Image.new('L', (W, H), 0)
    d = ImageDraw.Draw(m)
    for kind, v in shapes:
        if kind == 'e': d.ellipse((v[0] - v[2], v[1] - v[3], v[0] + v[2], v[1] + v[3]), fill=255)
        else: d.rectangle(v, fill=255)
    m = m.filter(ImageFilter.GaussianBlur(1.6))
    box = m.getbbox()
    sp = src.copy(); sp.putalpha(m)
    sp.crop(box).save(f'{out}/sprites/{name}.png', optimize=True)
    return list(box), m


knob_box, km = cut('knob', [('e', GEM), ('r', CAP)])
spring_box, sm = cut('spring', [('r', SPRING)])

# clear only what the moving knob uncovers: the gem + cap area (the cap slides down over the painted spring,
# so the spring area can stay as painted). Texture-aware fill from the lane around it.
pf = cv2.imread(f'{out}/playfield.jpg')
mask = (np.array(km) > 8).astype(np.uint8) * 255
mask = cv2.dilate(mask, np.ones((5, 5), np.uint8))
fixed = pf.copy()
cv2.xphoto.inpaint(pf, 255 - mask, fixed, cv2.xphoto.INPAINT_FSR_FAST)  # xphoto: 0 = missing
fixed = np.where(mask[..., None] > 0, cv2.GaussianBlur(fixed, (0, 0), 1.5), pf)
cv2.imwrite(f'{out}/playfield.jpg', fixed, [cv2.IMWRITE_JPEG_QUALITY, 92])

meta_path = f'{out}/sprites/sprites.json'
meta = json.load(open(meta_path))
meta['knob'] = {'box': knob_box, 'top': GEM[1] - GEM[3]}
meta['spring'] = {'box': spring_box}
json.dump(meta, open(meta_path, 'w'), indent=1)
with open(f'{out}/../js/render/sprite-meta.js', 'w') as fh:
    fh.write('// Generated by tools/prepare_art.py + tools/plunger_art.py – where each cut-out sprite sits in the painting.\nexport const SPRITES = ' + json.dumps(meta) + ';\n')
print('knob', knob_box, 'spring', spring_box)
