"""Rebalance the table: move mushroom 2 from the crowded left side to the open stone path on the right
(between the wizard and the crystal ramp). Run once, after prepare_art.py and plunger_art.py.

- clears the old spot in playfield.jpg with a nearby patch of the painting (seamless clone, no smudge)
- paints a soft contact shadow at the new spot (the mushroom sprite itself is drawn live on top)
- moves the mush2 sprite box/base in sprites.json + sprite-meta.js

Usage: python3 move_mush2.py <artdir>
"""
import sys, json
import numpy as np, cv2
from PIL import Image

out = sys.argv[1]
NEW_CENTRE = (880, 1215)  # where the mushroom sprite is centred now (painting pixels)
PATCH_OFFSET = (170, 60)  # take the fill from this far right/down of the old spot (grass and stones)

meta_path = f'{out}/sprites/sprites.json'
meta = json.load(open(meta_path))
old = meta['mush2']
b = old['box']
pf = cv2.imread(f'{out}/playfield.jpg')
alpha = np.array(Image.open(f'{out}/sprites/mush2.png').split()[-1])
mask = np.zeros(pf.shape[:2], np.uint8)
mask[b[1]:b[1] + alpha.shape[0], b[0]:b[0] + alpha.shape[1]] = (alpha > 8).astype(np.uint8) * 255
mask = cv2.dilate(mask, np.ones((35, 35), np.uint8))  # include its glow
ys, xs = np.where(mask > 0)
x0, y0, x1, y1 = xs.min() - 4, ys.min() - 4, xs.max() + 5, ys.max() + 5
dx, dy = PATCH_OFFSET
pf = cv2.seamlessClone(pf[y0 + dy:y1 + dy, x0 + dx:x1 + dx].copy(), pf, mask[y0:y1, x0:x1], ((x0 + x1) // 2, (y0 + y1) // 2), cv2.NORMAL_CLONE)

# contact shadow under the new spot
w, h = b[2] - b[0], b[3] - b[1]
nb = [NEW_CENTRE[0] - w // 2, NEW_CENTRE[1] - h // 2]
nb += [nb[0] + w, nb[1] + h]
base = [old['base'][0] - b[0] + nb[0], old['base'][1] - b[1] + nb[1]]
shadow = np.zeros(pf.shape[:2], np.float32)
cv2.ellipse(shadow, (base[0], base[1] - 2), (52, 14), 0, 0, 360, 1.0, -1)
shadow = cv2.GaussianBlur(shadow, (0, 0), 8) * 0.55
pf = (pf.astype(np.float32) * (1 - shadow[..., None])).astype(np.uint8)
cv2.imwrite(f'{out}/playfield.jpg', pf, [cv2.IMWRITE_JPEG_QUALITY, 92])

meta['mush2'] = {'box': nb, 'base': base}
json.dump(meta, open(meta_path, 'w'), indent=1)
with open(f'{out}/../js/render/sprite-meta.js', 'w') as fh:
    fh.write('// Generated by tools/prepare_art.py + plunger_art.py + move_mush2.py – where each cut-out sprite sits in the painting.\nexport const SPRITES = ' + json.dumps(meta) + ';\n')
print('mush2 moved: box', nb, 'base', base)
