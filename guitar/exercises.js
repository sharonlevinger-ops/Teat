  function spiderPattern(pat) {
    const up = [];
    for (let s = 6; s >= 1; s--) for (const f of pat) up.push(n(s, f));
    const down = [];
    for (let s = 1; s <= 6; s++) for (const f of [...pat].reverse()) down.push(n(s, f));
    return dedupe(up.concat(down));
  }
