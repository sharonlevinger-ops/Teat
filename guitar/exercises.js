  function dedupe(steps) {
    const same = (a, b) => a.s === b.s && a.f === b.f;
    const out = [];
    for (const x of steps) if (!out.length || !same(out[out.length - 1], x)) out.push(x);
    while (out.length > 1 && same(out[0], out[out.length - 1])) out.pop();
    return out;
  }

